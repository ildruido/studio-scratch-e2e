#!/usr/bin/env node
// Duplicate search for the harness-idea skill: one call instead of several searches.
//   node .claude/skills/harness-idea/dup-search.mjs <owner/repo> <name-or-keyword>...
// Searches open AND closed issues of app-studio for each term (skill, agent, hook, template or pack
// name, or a keyword), labelled or not, and prints at most ~20 lines: #number, state, labels,
// title, and for closed issues the closing comment. The model keeps the final judgement.
// Needs the GitHub access the session already has (`gh`); exits 2 if the search can't run, so the
// skill falls back to searching by hand.
import { spawnSync } from "node:child_process";
import { pathToFileURL } from "node:url";

const MAX_TERMS = 6;
const MAX_LINES = 20;
const IDEA_LABELS = ["harness-idea", "studio-backlog"];

function ghApi(args) {
  const r = spawnSync("gh", ["api", ...args], { encoding: "utf8", maxBuffer: 20 * 1024 * 1024 });
  if (r.error || r.status !== 0) throw new Error((r.stderr || r.error?.message || "gh failed").trim().split("\n")[0]);
  return JSON.parse(r.stdout);
}

const defaultApi = {
  search: (q) => ghApi(["-X", "GET", "search/issues", "-f", `q=${q}`, "-f", "per_page=15"]).items,
  comments: (repo, n) => ghApi(["-X", "GET", `repos/${repo}/issues/${n}/comments`, "-f", "per_page=100"]),
};

const clip = (s, n) => {
  const t = String(s ?? "").replace(/\s+/g, " ").trim();
  return t.length > n ? t.slice(0, n - 1) + "…" : t;
};

/** Pure core: returns the output lines. `api` is injectable for tests. */
export function dupSearch(repo, terms, api = defaultApi) {
  const found = new Map();
  for (const term of terms.slice(0, MAX_TERMS)) {
    const q = `repo:${repo} is:issue "${term.replace(/"/g, "")}"`;
    for (const it of api.search(q)) {
      const e = found.get(it.number) ?? { it, hits: 0 };
      e.hits++;
      found.set(it.number, e);
    }
  }
  const rank = ([, e]) => {
    const labels = (e.it.labels ?? []).map((l) => l.name ?? l);
    const idea = labels.some((l) => IDEA_LABELS.includes(l)) || /^\[harness-idea\]/i.test(e.it.title);
    return e.hits * 4 + (idea ? 2 : 0) + (e.it.state === "open" ? 1 : 0);
  };
  const top = [...found].sort((a, b) => rank(b) - rank(a) || b[0] - a[0]).slice(0, MAX_LINES);
  const lines = [];
  for (const [n, { it }] of top) {
    const labels = (it.labels ?? []).map((l) => l.name ?? l).filter((l) => IDEA_LABELS.includes(l));
    let line = `#${n} ${it.state} [${labels.join(",") || "no label"}] ${clip(it.title, 90)}`;
    if (it.state === "closed") {
      let last = "";
      try {
        const c = api.comments(repo, n);
        last = c.length ? c[c.length - 1].body.replace(/\s*---\s*_Generated by[\s\S]*$/, "") : "";
      } catch { /* shown as no comment */ }
      line += ` | closing comment: ${last ? clip(last, 140) : "(none)"}`;
    }
    lines.push(line);
  }
  return lines;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [repo, ...terms] = process.argv.slice(2);
  if (!repo || !/^[\w.-]+\/[\w.-]+$/.test(repo) || !terms.length) {
    console.error("Usage: dup-search.mjs <owner/repo> <name-or-keyword>...");
    process.exit(2);
  }
  try {
    const lines = dupSearch(repo, terms);
    console.log(lines.length ? lines.join("\n") : "No matching issues found.");
  } catch (e) {
    console.error(`Search unavailable (${e.message}). Search the issues by hand as the skill says.`);
    process.exit(2);
  }
}
